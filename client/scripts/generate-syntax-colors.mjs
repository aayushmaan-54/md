// Generates src/editor/syntax-colors.generated.ts from shiki's bundled
// github-light/github-dark themes. Re-run via `npm run generate:syntax-colors`
// after bumping the `shiki` dependency.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { bundledThemes } from "shiki";

const SCOPES = [
  "comment",
  "keyword",
  "string",
  "constant",
  "entity",
  "support",
  "entity.name.tag",
  "variable.other",
  "invalid.illegal",
  "markup.heading",
  "markup.bold",
  "markup.italic",
  "string.other.link",
  "markup.inline.raw",
];

function scopeColor(theme, scope) {
  for (const rule of theme.tokenColors ?? []) {
    const scopes = Array.isArray(rule.scope) ? rule.scope : rule.scope ? [rule.scope] : [];
    if (scopes.includes(scope)) return rule.settings?.foreground;
  }
  return undefined;
}

async function extractColors(themeName) {
  const { default: theme } = await bundledThemes[themeName]();
  const colors = {};
  for (const scope of SCOPES) {
    const color = scopeColor(theme, scope);
    if (!color) {
      throw new Error(`No color found for scope "${scope}" in theme "${themeName}"`);
    }
    colors[scope] = color;
  }
  return colors;
}

const [light, dark] = await Promise.all([
  extractColors("github-light"),
  extractColors("github-dark"),
]);

const outPath = fileURLToPath(
  new URL("../src/editor/syntax-colors.generated.ts", import.meta.url),
);

const render = (colors) =>
  Object.entries(colors)
    .map(([scope, color]) => `  "${scope}": "${color}",`)
    .join("\n");

const contents = `// AUTO-GENERATED by scripts/generate-syntax-colors.mjs — do not edit by hand.

export const lightSyntaxColors = {
${render(light)}
} as const;

export const darkSyntaxColors = {
${render(dark)}
} as const;
`;

writeFileSync(outPath, contents);
console.log(`Wrote ${outPath}`);
